export const ICON_NAMES = Object.keys(P);

export function icon(name, { className = '', label } = {}) {
  const body = P[name];
  if (!body) throw new Error(`Ikonka topilmadi: ${name}`);
  const a11y = label ? `role="img" aria-label="${label}"` : 'aria-hidden="true" focusable="false"';
  return `<svg class="icon ${className}" viewBox="0 0 24 24" ${a11y}>${body}</svg>`;
}

// HTML ichidagi <i data-icon="search"></i> belgilarini SVG bilan almashtiradi.
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    el.outerHTML = icon(el.dataset.icon, { className: el.dataset.iconClass || '', label: el.dataset.iconLabel });
  });
}
